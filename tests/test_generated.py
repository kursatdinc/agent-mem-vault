import yaml

from agent_mem_vault.generated import DASHBOARD_RELPATH


def read(vault, relpath):
    return (vault.root / relpath).read_text(encoding="utf-8")


def test_the_hub_groups_records_by_kind_newest_first_with_a_generated_banner(store, vault):
    first = store.save_context(agent="a", title="First note", content="c", namespace="project/alpha")
    decision = store.save_memory(
        agent="a", kind="decision", title="Pick | storage", content="c", namespace="project/alpha"
    )
    second = store.save_context(agent="a", title="Second note", content="c", namespace="project/alpha")
    store.save_context(agent="a", title="Elsewhere", content="c", namespace="beta")

    assert read(vault, "project-alpha/project-alpha.md") == (
        "---\n"
        "namespace: project/alpha\n"
        "title: 'Memory index: project/alpha'\n"
        "agent-written: true\n"
        "generated: true\n"
        "---\n"
        "> Generated by agent-mem-vault. Do not edit: changes are overwritten on the next write.\n"
        "\n"
        "# project/alpha\n"
        "\n"
        "## note\n"
        "\n"
        f"- [[{second.path.removesuffix('.md')}|Second note]] (2026-10-28)\n"
        f"- [[{first.path.removesuffix('.md')}|First note]] (2026-10-28)\n"
        "\n"
        "## decision\n"
        "\n"
        f"- [[{decision.path.removesuffix('.md')}|Pick storage]] (2026-10-28)\n"
    )
    assert "Elsewhere" not in read(vault, "project-alpha/project-alpha.md")
    assert "- [[beta/note/" in read(vault, "beta/beta.md")


def test_the_hub_is_not_a_record_and_an_unchanged_hub_is_not_rewritten(store, vault):
    store.save_context(agent="a", title="Only note", content="c", namespace="proj")
    hub = vault.root / "proj" / "proj.md"
    before = hub.stat().st_mtime_ns
    text = hub.read_text(encoding="utf-8")

    with vault.lock():
        changed = vault.write_generated("proj/proj.md", text)

    assert changed is False
    assert hub.stat().st_mtime_ns == before
    assert [record.title for record in vault.scan().records] == ["Only note"]
    assert vault.scan().issues == []


def test_a_hub_path_holding_a_note_a_human_wrote_is_left_alone_and_the_write_still_succeeds(store, vault, capsys):
    (vault.root / "proj").mkdir()
    (vault.root / "proj" / "proj.md").write_text("# My own index\n", encoding="utf-8")

    record = store.save_context(agent="a", title="Kept", content="c", namespace="proj")

    assert read(vault, "proj/proj.md") == "# My own index\n"
    assert read(vault, record.path).startswith("---\nid: ")
    assert "refusing to overwrite a file that is not generated: proj/proj.md" in capsys.readouterr().err


def test_a_hub_that_cannot_be_written_never_fails_the_write(store, vault, capsys):
    (vault.root / "proj" / "proj.md").mkdir(parents=True)

    record = store.save_context(agent="a", title="Still saved", content="c", namespace="proj")

    assert store.get_last_context("proj").id == record.id
    assert "could not refresh generated notes" in capsys.readouterr().err


def test_the_dashboard_is_created_with_the_documented_bases_views(store, vault):
    store.save_context(agent="a", title="First", content="c", namespace="proj")

    base = yaml.safe_load(read(vault, DASHBOARD_RELPATH))

    assert set(base) == {"filters", "views"}
    assert base["filters"] == {"and": ['note["agent-written"] == true']}
    assert [(view["type"], view["name"]) for view in base["views"]] == [
        ("table", "Pending handoffs"),
        ("table", "Decisions and risks"),
        ("table", "All records"),
    ]
    pending, decisions, everything = base["views"]
    assert pending["filters"] == {"and": ['note.kind == "handoff"', "note.read == false"]}
    assert decisions["filters"] == {
        "and": [{"or": ['note.kind == "decision"', 'note.kind == "risk"']}, 'note.validity == "valid"']
    }
    assert decisions["groupBy"] == {"property": "note.namespace", "direction": "ASC"}
    assert everything["order"] == ["note.title", "note.kind", "note.namespace", "note.created", "note.status"]


def test_an_existing_dashboard_is_never_overwritten(store, vault):
    store.save_context(agent="a", title="First", content="c", namespace="proj")
    (vault.root / DASHBOARD_RELPATH).write_text("filters: {}\nviews: []\n", encoding="utf-8")

    store.save_context(agent="a", title="Second", content="c", namespace="proj")

    assert read(vault, DASHBOARD_RELPATH) == "filters: {}\nviews: []\n"


def test_a_write_into_a_fresh_vault_produces_the_record_the_hub_and_the_dashboard(store, vault):
    record = store.save_context(agent="a", title="Hello", content="World.", namespace="proj")

    produced = sorted(path.relative_to(vault.root).as_posix() for path in vault.root.rglob("*") if path.is_file())

    assert produced == [
        ".agent-mem-vault/lock",
        "_dashboards/memory.base",
        record.path,
        "proj/proj.md",
    ]
