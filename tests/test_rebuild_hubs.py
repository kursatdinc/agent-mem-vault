import os
import shutil
import subprocess

import pytest

from agent_mem_vault.cli import main
from agent_mem_vault.store import Store
from agent_mem_vault.vault import Vault
from conftest import TickingClock

THREAD = "- main: wiring; next: test"
DASHBOARD_LINE = "Dashboard: [[_dashboards/memory.base|memory dashboard]]\n"


def read(root, relpath):
    return (root / relpath).read_text(encoding="utf-8")


def make_stale(root, slug):
    """Cut a hub back to the 2.0.0 shape: record groups only, no companion section and no dashboard line."""
    hub = root / slug / f"{slug}.md"
    hub.write_text(read(root, f"{slug}/{slug}.md").split("\n\n## companion")[0].split("\n\nDashboard:")[0] + "\n")


def git(cwd, *args):
    return subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=True).stdout.strip()


@pytest.fixture
def stale_vault(configured_vault):
    """alpha: a decision and a card, stale hub; project/beta: only a card, no hub yet; gamma: a current hub."""
    root = configured_vault.root
    store = Store(configured_vault, clock=TickingClock(), companion_max_chars=100)
    store.save_memory(agent="a", kind="decision", title="Pick storage", content="c", namespace="alpha")
    store.update_companion("alpha", threads=THREAD)
    store.update_companion("project/beta", last_session="Started.")
    store.save_context(agent="a", title="Kept", content="c", namespace="gamma")
    make_stale(root, "alpha")
    (root / "project-beta" / "project-beta.md").unlink()
    (root / "Journal").mkdir()
    (root / "Journal" / "today.md").write_text("mine\n", encoding="utf-8")
    return configured_vault


def test_rebuild_hubs_without_slugs_rebuilds_every_namespace_folder_and_prints_each_touched_file(stale_vault, capsys):
    root = stale_vault.root
    gamma_before = read(root, "gamma/gamma.md")

    assert main(["rebuild-hubs"]) == 0

    assert capsys.readouterr().out.splitlines() == ["wrote alpha/alpha.md", "wrote project-beta/project-beta.md"]
    assert read(root, "alpha/alpha.md").endswith(
        f"## companion\n\n- [[alpha/_companion/threads|threads]]\n\n{DASHBOARD_LINE}"
    )
    assert read(root, "project-beta/project-beta.md") == (
        "---\nnamespace: project/beta\ntitle: 'Memory index: project/beta'\nagent-written: true\ngenerated: true\n"
        "---\n> Generated by agent-mem-vault. Do not edit: changes are overwritten on the next write.\n\n"
        "# project/beta\n\n## companion\n\n"
        f"- [[project-beta/_companion/last-session|last-session]]\n\n{DASHBOARD_LINE}"
    )
    assert read(root, "gamma/gamma.md") == gamma_before
    assert sorted(path.name for path in root.iterdir()) == [
        ".agent-mem-vault",
        "Journal",
        "_dashboards",
        "alpha",
        "gamma",
        "project-beta",
    ]
    assert read(root, "Journal/today.md") == "mine\n"

    assert main(["rebuild-hubs"]) == 0
    assert capsys.readouterr().out == "Hubs are up to date.\n"


def test_rebuild_hubs_with_slugs_touches_only_those_and_reports_unknown_ones(stale_vault, capsys):
    root = stale_vault.root
    make_stale(root, "gamma")
    stale_gamma = read(root, "gamma/gamma.md")

    assert main(["rebuild-hubs", "alpha", "nope", "_dashboards"]) == 0

    output = capsys.readouterr()
    assert output.out.splitlines() == ["wrote alpha/alpha.md"]
    assert output.err.splitlines() == [
        "agent-mem-vault: no namespace folder named nope: skipped",
        "agent-mem-vault: no namespace folder named _dashboards: skipped",
    ]
    assert read(root, "alpha/alpha.md").endswith(DASHBOARD_LINE)
    assert read(root, "gamma/gamma.md") == stale_gamma
    assert not (root / "project-beta" / "project-beta.md").exists()


def emptied(store, namespace):
    """A namespace whose only record was deleted by hand, leaving its generated hub behind."""
    record = store.save_context(agent="a", title="Gone", content="c", namespace=namespace)
    shutil.rmtree(store.vault.root / record.path.rsplit("/", 2)[0] / "note")


def test_an_emptied_namespace_loses_its_generated_hub_and_its_empty_folder_but_never_a_user_note(
    configured_vault, capsys
):
    root = configured_vault.root
    store = Store(configured_vault, clock=TickingClock())
    for namespace in ("gone", "half", "mine"):
        emptied(store, namespace)
    (root / "half" / "notes.md").write_text("mine\n", encoding="utf-8")
    (root / "mine" / "mine.md").write_text("# My own index\n", encoding="utf-8")

    assert main(["rebuild-hubs"]) == 0

    assert capsys.readouterr().out.splitlines() == ["removed gone/gone.md", "removed half/half.md"]
    assert not (root / "gone").exists()
    assert sorted(path.name for path in (root / "half").iterdir()) == ["notes.md"]
    assert read(root, "mine/mine.md") == "# My own index\n"


def test_rebuild_hubs_commits_the_touched_files_only_with_git_autocommit_on(stale_vault, capsys):
    root = stale_vault.root
    git(root, "init", "-q", "-b", "main")
    git(root, "config", "user.name", "Dana Tester")
    git(root, "config", "user.email", "dana@example.invalid")
    git(root, "config", "commit.gpgsign", "false")
    (root / ".gitignore").write_text(".agent-mem-vault/\n", encoding="utf-8")
    Store(stale_vault, clock=TickingClock()).save_context(agent="a", title="Gone", content="c", namespace="gone")
    shutil.rmtree(root / "gone" / "note")
    git(root, "add", "-A")
    git(root, "reset", "-q", "--", "gone/gone.md")
    git(root, "commit", "-q", "-m", "before")

    assert main(["rebuild-hubs", "alpha"]) == 0
    assert capsys.readouterr().out == "wrote alpha/alpha.md\n"
    assert git(root, "rev-list", "--count", "HEAD") == "1"
    git(root, "checkout", "-q", "--", "alpha/alpha.md")

    config_file = os.environ["AGENT_MEM_VAULT_CONFIG"]
    with open(config_file, "w", encoding="utf-8") as handle:
        handle.write("features:\n  git_autocommit: true\n")
    assert main(["rebuild-hubs"]) == 0

    out = capsys.readouterr().out.splitlines()
    assert out == ["wrote alpha/alpha.md", "removed gone/gone.md", "wrote project-beta/project-beta.md"]
    assert git(root, "log", "-1", "--format=%s") == "avm: rebuild hubs"
    assert sorted(git(root, "show", "--name-status", "--format=", "HEAD").splitlines()) == [
        "A\tproject-beta/project-beta.md",
        "M\talpha/alpha.md",
    ]
    assert git(root, "status", "--porcelain") == ""


def test_the_vault_store_api_rebuilds_hubs_for_a_sync_script(tmp_path):
    root = tmp_path / "vault"
    root.mkdir()
    store = Store(Vault(root), clock=TickingClock())
    store.save_context(agent="a", title="Kept", content="c", namespace="proj")
    make_stale(root, "proj")

    assert store.rebuild_hubs(["proj", "nope"]) == (["proj/proj.md"], ["nope"])
    assert store.rebuild_hubs() == ([], [])
