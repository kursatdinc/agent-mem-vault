from agent_mem_vault.records import KINDS, RECEIPT_KIND, Record, namespace_slug, render_record, wikilink

HUB_BANNER = "> Generated by agent-mem-vault. Do not edit: changes are overwritten on the next write."
DASHBOARD_RELPATH = "_dashboards/memory.base"

DASHBOARD = """\
filters:
  and:
    - 'note["agent-written"] == true'
views:
  - type: table
    name: "Active decisions and risks"
    filters:
      and:
        - or:
            - 'note.kind == "decision"'
            - 'note.kind == "risk"'
        - 'note.validity == "valid"'
        - 'note.status != "superseded"'
        - 'note.status != "resolved"'
    groupBy:
      property: note.namespace
      direction: ASC
    order:
      - file.name
      - note.kind
      - note.status
      - note.review_by
      - note.created
  - type: table
    name: "All records"
    filters:
      and:
        - 'note.generated != true'
    order:
      - note.title
      - note.kind
      - note.namespace
      - note.created
      - note.status
"""


def hub_relpath(namespace: str) -> str:
    slug = namespace_slug(namespace)
    return f"{slug}/{slug}.md"


def render_hub(namespace: str, records: list[Record], cards: list[str]) -> str:
    """Deterministic hub note: records grouped by kind, newest first, then the given companion card paths and the
    dashboard, so an unchanged namespace renders identically and no note the server writes is a graph orphan.

    Records of the same second are ordered by path, not by file time, which differs on each synced machine.
    """
    meta = {"title": f"Memory index: {namespace}", "namespace": namespace, "generated": True, "agent-written": True}
    lines = [HUB_BANNER, "", f"# {namespace}"]
    for kind in (*KINDS, RECEIPT_KIND):
        group = sorted(
            (record for record in records if record.kind == kind), key=lambda r: (r.created, r.path), reverse=True
        )
        if group:
            lines += ["", f"## {kind}", ""]
            lines += [f"- {wikilink(record.path, record.title)} ({record.created[:10]})" for record in group]
    if cards:
        lines += ["", "## companion", ""]
        lines += [f"- {wikilink(card, card.rsplit('/', 1)[-1].removesuffix('.md'))}" for card in cards]
    lines += ["", f"Dashboard: {wikilink(DASHBOARD_RELPATH, 'memory dashboard')}"]
    return render_record(meta, "\n".join(lines) + "\n")
