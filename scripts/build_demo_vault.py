"""Regenerate examples/demo-vault with the project's own store API.

Every record is synthetic: two fictional projects, fixed ids and a fixed clock, so running this script twice
produces byte-identical files.

    uv run python scripts/build_demo_vault.py [target-directory]
"""

import shutil
import sys
import tempfile
import uuid
from datetime import UTC, datetime, timedelta
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch

from agent_mem_vault import store as store_module
from agent_mem_vault.store import Store
from agent_mem_vault.vault import STATE_DIR, Vault

DEFAULT_TARGET = Path(__file__).resolve().parent.parent / "examples" / "demo-vault"
START = datetime(2026, 3, 2, 9, 0, 0, tzinfo=UTC)

OBSIDIAN_APP_JSON = '{\n  "alwaysUpdateLinks": true\n}\n'

WELCOME = """\
# Demo vault

Synthetic memory for two fictional projects, `project/harbor-api` and `project/lantern-mobile`.
Generated by `scripts/build_demo_vault.py`; nothing here is real.

Open this folder as a vault in Obsidian, then:

- open the graph view to see the supersedes chains and the project hubs,
- open `_dashboards/memory.base` for pending handoffs, open decisions and risks,
- edit any record and run `agent-mem-vault doctor` to see the change picked up.
"""


class DemoClock:
    """Each call is one minute after the previous one; `day` jumps to 09:00 of a later day."""

    def __init__(self) -> None:
        self.moment = START

    def __call__(self) -> datetime:
        self.moment += timedelta(minutes=1)
        return self.moment

    def day(self, offset: int) -> None:
        self.moment = START + timedelta(days=offset)


class DemoIds:
    """Deterministic stand-in for uuid4 inside the store module."""

    def __init__(self) -> None:
        self.counter = 0

    def uuid4(self) -> uuid.UUID:
        self.counter += 1
        return uuid.uuid5(uuid.NAMESPACE_URL, f"agent-mem-vault/demo/{self.counter}")


def _harbor_api(store: Store, clock: DemoClock) -> None:
    ns = "project/harbor-api"
    clock.day(0)
    sqlite = store.save_memory(
        "claude-code",
        "decision",
        "Use SQLite for the first release",
        "Orders fit on one node for the pilot. SQLite keeps deployment to a single file and needs no extra service.",
        ns,
        status="superseded",
        tags=["storage"],
    )
    cache = store.save_memory(
        "claude-code",
        "decision",
        "Cache order lookups in process memory",
        "A per-process dict would cut the lookup latency without any new infrastructure.",
        ns,
        tags=["performance"],
    )
    clock.day(1)
    store.update_memory(
        cache.id,
        validity="rejected",
        rejected_reason="Workers do not share memory, so cached orders go stale between processes.",
    )
    clock.day(4)
    postgres = store.save_memory(
        "claude-code",
        "decision",
        "Move order storage to PostgreSQL",
        "The pilot grew to three workers, which SQLite cannot serve safely. PostgreSQL gives concurrent writers "
        "and point-in-time recovery.",
        ns,
        status="accepted",
        tags=["storage"],
        supersedes=[sqlite.id],
    )
    clock.day(6)
    store.save_memory(
        "codex",
        "decision",
        "Pin PostgreSQL 16 in CI and production",
        "CI uses the same major version as production so migration scripts behave identically.",
        ns,
        status="accepted",
        tags=["storage", "ci"],
        supersedes=[postgres.id],
    )
    store.save_memory(
        "codex",
        "risk",
        "Migration script locks the orders table",
        "The backfill runs inside one transaction and holds a lock on `orders` for about 40 seconds on a copy of "
        "production data. Writes queue up behind it.",
        ns,
        status="open",
        related_files=["migrations/0007_backfill_orders.sql"],
        next_action="Split the backfill into batches of 5000 rows",
        tags=["storage", "migration"],
    )

    clock.day(7)
    first = store.create_handoff(
        "codex",
        "Batch the orders backfill",
        "The backfill in migrations/0007 needs batching. Start with a batch size of 1000 and measure the lock time.",
        ns,
    )
    store.create_handoff(
        "claude-code",
        "Review the new retry policy",
        "The retry policy for the payment webhook is ready. Please review the backoff values.",
        ns,
    )
    store.read_handoff("claude-code", ns)
    clock.day(8)
    store.create_handoff(
        "codex",
        "Batch the orders backfill, revised",
        "Batches of 5000 rows tested better than 1000. Keep the transaction per batch and add a progress log line.",
        ns,
        supersedes=[first.id],
    )
    store.create_snapshot(
        "claude-code",
        "harbor-api state after the PostgreSQL move",
        "Storage runs on PostgreSQL 16. The orders backfill is the one open risk and is handed to Codex. The "
        "in-process cache idea was rejected.",
        ns,
    )


def _lantern_mobile(store: Store, clock: DemoClock) -> None:
    ns = "project/lantern-mobile"
    clock.day(2)
    store.save_memory(
        "claude-code",
        "decision",
        "Sync offline first, reconcile on reconnect",
        "Field staff work in tunnels with no signal. The app writes locally and reconciles when the network "
        "returns, with last-writer-wins per field.",
        ns,
        status="accepted",
        tags=["sync"],
    )
    store.save_memory(
        "codex",
        "risk",
        "Push token refresh fails silently on one Android version",
        "On Android 14 the refreshed token is not sent to the backend when the app is in the background. "
        "Notifications stop until the next cold start.",
        ns,
        status="open",
        tags=["notifications", "android"],
    )
    store.save_context(
        "claude-code",
        "Release checklist for the beta",
        "Bump the build number, run the offline smoke test, and attach the sync log to the release notes.",
        ns,
        tags=["release"],
    )
    clock.day(5)
    store.create_handoff(
        "claude-code",
        "Reproduce the push token bug",
        "Codex found the symptom on a Pixel emulator running Android 14. Please reproduce it on a real device "
        "and capture the token refresh log.",
        ns,
    )
    store.create_snapshot(
        "codex",
        "lantern-mobile beta status",
        "Offline sync works end to end. One notification risk is open and handed to Claude Code.",
        ns,
    )


def build(target: Path) -> None:
    """Build the demo vault in a scratch directory outside any git work tree, then copy it into `target`."""
    ids = DemoIds()
    with tempfile.TemporaryDirectory() as scratch, patch.object(store_module, "uuid", SimpleNamespace(uuid4=ids.uuid4)):
        root = Path(scratch) / "demo-vault"
        root.mkdir()
        clock = DemoClock()
        store = Store(Vault(root), clock=clock)
        _harbor_api(store, clock)
        _lantern_mobile(store, clock)
        shutil.rmtree(root / STATE_DIR)
        (root / ".obsidian").mkdir()
        (root / ".obsidian" / "app.json").write_text(OBSIDIAN_APP_JSON, encoding="utf-8")
        (root / "README.md").write_text(WELCOME, encoding="utf-8")
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(root, target)


def main(argv: list[str]) -> int:
    target = Path(argv[0]) if argv else DEFAULT_TARGET
    build(target)
    print(f"demo vault written to {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
